-- 6. CRIAR POLÍTICAS SEGURAS (RLS)

-- Despesas: Cada usuário só gerencia as suas próprias
CREATE POLICY "Users can manage their own expenses" 
ON public.expenses 
FOR ALL 
TO authenticated 
USING (auth.uid() = user_id) 
WITH CHECK (auth.uid() = user_id);

-- Receitas: Cada usuário só gerencia as suas próprias
CREATE POLICY "Users can manage their own incomes" 
ON public.incomes 
FOR ALL 
TO authenticated 
