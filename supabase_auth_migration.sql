-- 1. CRIAR AS TABELAS CASO NÃO EXISTAM (COM user_id VINCULADO AO AUTH)
CREATE TABLE IF NOT EXISTS public.expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    description text NOT NULL,
    company text,
    amount numeric(10, 2) NOT NULL,
    paid_amount numeric(10, 2) DEFAULT 0,
    due_date date NOT NULL,
    paid_date date,
    payment_method text,
    notes text,
    excess_type text,
    bill_attachment text,
    bill_name text,
    receipt_attachment text,
    receipt_name text,
    type text NOT NULL DEFAULT 'Outros',
    status text NOT NULL CHECK (status IN ('pending', 'paid')) DEFAULT 'pending',
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.incomes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    source text NOT NULL,
    amount numeric(10, 2) NOT NULL,
    date text NOT NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.expense_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    name text NOT NULL,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.companies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    name text NOT NULL,
    default_type text NOT NULL DEFAULT 'Outros',
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.investments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    asset text NOT NULL,
    category text NOT NULL DEFAULT 'Renda Fixa',
    amount numeric(10, 2) NOT NULL,
    date text NOT NULL,
    notes text,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

